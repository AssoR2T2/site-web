                <h3>Comment est ce que je peux créer un compte?</h3>
            </summary>
            Pour créer un compte admin il faut avoir access au coté admin puis aller sur "SignIn" en haut a droite ou bien en cliquant <a class="lien-a" href="Inscription-administrateur">'ici'</a>. 
            Puis entrer les information comme nom, prénom, email, mot de passe et confirmation de mot de passe (Pas nécessaire en cas de modification de l'utilisateur).
        </details>

        <details class="faq-detail">
            <summary id="singal-objet">
                 <h3>Comment peut-on signaler un objet perdu/retrouver?</h3>
            </summary>
            Il faudra dans un premier temps avoir créé un compte (information pour <a class="lien-a" href="#creer-compte">'créer un compte'</a>), 
            ensuite il faudra soit depuis l'acceuil et cliquer sur le bouton "Signalez", 
            soit en cliquant sur signalement du menu soit en cliquant 
            <a class="lien-a" name="page" href="Signalement-administrateur">'ici'</a>.
            Il faudra ensuite remplir les cases du formulaire puis cliquer sur "validé". 
            
        </details>


        <details class="faq-detail">
            <summary id="ban-util">
            <h3>Comment peut-on bannir/débannir un utilisateur?</h3>
            </summary>
        Pour pouvoir bannir un utilisateur il faut soit aller dans "Listes des Utilisateurs" ou cliquer <a class="lien-a" href="Liste-Utilisateur-administrateur">'ici'</a>, soit depuis un objet dans l'onglet "Recherche". 
        Depuis ces deux pages, il y a dans "Listes des Utilisateurs" un tableau avec divers information ou bouton, parmis ces boutons il y a un bouton bannir ou débannir (si il est déjà banni), depuis un objet dans recherche il y a le bouton rouge permettant uniquement de bannir l'utilisateur.
    
    </details>



    <details class="faq-detail">
            <summary id="modif-util">
            <h3>Comment modifier un utilisateur du site?</h3>

            </summary>
            Pour modifier un utilisateur il faut passer par "Listes des Utilisateurs" ou cliquer <a class="lien-a" href="Liste-Utilisateur-administrateur">'ici'</a> puis chercher la personne ou les personnes que vous voulez modifier puis cliquer sur le bouton "Modifier" présent sur la ligne de l'utilisateur choisi. 
            Le bouton vous renvoie sur une page avec un fonctionnement équivalent a la page pour créer un compte (Pour les information pour creer un compte cliquer <a class="lien-a" name="page" href="#creer-compte">'ici'</a>) Si aucun problème c'est produit vous avez modifier un utilisateur.
        </details>

        <details class="faq-detail">
            <summary id="sup-util">
            <h3>Comment supprimer un utilisateur du site?</h3>

            </summary>
            Pour supprimer un utilisateur il faut passer par "Listes des Utilisateurs" ou cliquer <a class="lien-a" href="Liste-Utilisateur-administrateur">'ici'</a> puis chercher la personne ou les personnes que vous voulez supprimer puis cliquer sur le bouton supprimer présent sur la ligne de l'utilisateur choisi. Si aucun problème c'est produit vous avez supprimer un utilisateur.
        </details>


        <details class="faq-detail">
            <summary id="modif-objet">
            <h3>Comment modifier un objet?</h3>

            </summary>
            Pour modifier un objet, si c'est le votre vous avez deux possibilités, la première sera universel, aller dans "Recherche" ou <a class="lien-a" href="Recherche-administrateur">'ici'</a> puis clicker sur l'objet que vous voulez modifier, ensuite appuyer sur le bouton modifier et cela vous redirige sur une page signalement (suivez les instruction pour signaler un objet <a class="lien-a" name="page" href="#singal-objet">'ici'</a>).
        </details>


        <details class="faq-detail">
            <summary id="sup-objet">
            <h3>Comment supprimer un objet?</h3>
            </summary>
            Pour supprimer un objet aller dans "Recherche" ou <a class="lien-a" href="Recherche-administrateur">'ici'</a> puis chercher l'objet que vous voulez supprimer puis clicker sur le bouton supprimer.
        </details>
        
        
        
